import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const definition = JSON.parse(
  await readFile(resolve(here, "h0-report-descriptor.json"), "utf8"),
);

const le16 = (value) => [value & 0xff, (value >> 8) & 0xff];
const descriptor = Buffer.from([
  0x06, ...le16(definition.usagePage), // Usage Page (vendor-defined)
  0x09, definition.usage,             // Usage
  0xa1, 0x01,                         // Collection (Application)
  0x85, definition.inputReportId,
  0x09, 0x02,
  0x15, 0x00,
  0x26, 0xff, 0x00,
  0x75, 0x08,
  0x95, definition.payloadBytes,
  0x81, 0x02,                         // Input (Data, Variable, Absolute)
  0x85, definition.outputReportId,
  0x09, 0x03,
  0x15, 0x00,
  0x26, 0xff, 0x00,
  0x75, 0x08,
  0x95, definition.payloadBytes,
  0x91, 0x02,                         // Output (Data, Variable, Absolute)
  0xc0,
]);

const header = `// Generated by firmware/descriptors/generate.mjs; do not edit.\n` +
  `#ifndef AGENT_BRIDGE_H0_REPORT_DESCRIPTOR_H\n` +
  `#define AGENT_BRIDGE_H0_REPORT_DESCRIPTOR_H\n\n` +
  `#include <stdint.h>\n\n` +
  `static const uint8_t H0_REPORT_DESCRIPTOR[] = {\n` +
  descriptor.toString("hex").match(/.{2}/g)
    .map((byte, index) => `${index % 12 === 0 ? "    " : ""}0x${byte}${index + 1 === descriptor.length ? "" : ","}${index % 12 === 11 ? "\n" : " "}`)
    .join("").trimEnd() +
  `\n};\n\n#endif\n`;

const outputs = [
  [resolve(here, "h0-report-descriptor.bin"), descriptor],
  [resolve(here, "../generated/h0_report_descriptor.h"), Buffer.from(header)],
];

if (process.argv.includes("--check")) {
  for (const [path, expected] of outputs) {
    const actual = await readFile(path).catch(() => null);
    if (actual === null || !actual.equals(expected)) {
      throw new Error(`${path} is stale; run node firmware/descriptors/generate.mjs`);
    }
  }
} else {
  for (const [path, bytes] of outputs) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, bytes);
  }
}
